#!/bin/bash
# Пока источник модели переключён на MLX 5bit: прогнать замер сжатия, затем вернуть основную очередь.
# Основная очередь на 4-битной версии не пойдёт, пока Андрей не переключит источник обратно, —
# раннер проверяет вариант и остановится с ошибкой, а не запишет чужие веса.
cd "$(dirname "$0")/.." || exit 1
PY=.venv/bin/python
stamp() { echo "=== $(date '+%d.%m %H:%M') $*"; }
stamp "жду остановки основной очереди (pid $1)"
while kill -0 "$1" 2>/dev/null; do sleep 15; done
$PY src/night.py start queues/variant5bit.toml || { stamp "замер сжатия не стартовал"; exit 1; }
stamp "замер 5 бит запущен"
