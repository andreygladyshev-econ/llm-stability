"""Форма для ручной разметки отчёта человеком → {report}_ANDREY.csv + памятка в рабочей папке автора
(_АНДРЕЙ/4_разметка рядом с проектом, в репозиторий не входит).

Запуск: .venv/bin/python src/make_labeling_form.py 2026_q2 [версия_спеки]
Форма НЕ содержит оценок модели: эталон должен быть независимым, иначе он не эталон.
Сравнение с прогонами — src/compare_gold.py (после заполнения).
"""
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from indicators import INDICATORS

ROOT = Path(__file__).resolve().parent.parent
ANDREY = ROOT.parent / "_АНДРЕЙ"  # папка Андрея лежит рядом с проектом, не внутри
OUT = ANDREY / "4_разметка"

RULES = {  # краткая подсказка по правилу v2_inplace, чтобы не листать спеку
    "net_profit": "квартал г/г; >15% → ±2, 3–15% → ±1, <3% → 0",
    "eps": "квартал г/г; часто не указана → 0",
    "roe": "квартал г/г, в п.п.: >1,5 → ±2, 0,3–1,5 → ±1",
    "guidance": "оценивается ИЗМЕНЕНИЕ прогноза: подтвердили +1, сняли/понизили −2, нет прогноза 0",
    "nii": "квартал г/г",
    "fee_income": "квартал г/г",
    "nim": "квартал, в п.п.",
    "opex": "разрыв = рост операционного дохода до резервов − рост расходов: ±1 п.п. → 0, 1–10 → ±1, >10 → ±2",
    "cir": "снижение = плюс; уровень без динамики считается только при оценочной фразе в отчёте",
    "cor": "снижение = плюс; <0,2 п.п. → 0, 0,2–0,5 → ±1, >0,5 → ±2",
    "provisions": "рост резервов = минус, снижение = плюс; квартал г/г",
    "portfolio_quality": "меньше проблемных кредитов = плюс",
    "corporate_loans": "изменение с начала года, без валютной переоценки",
    "retail_loans": "изменение с начала года, без валютной переоценки",
    "customer_funds": "изменение с начала года, без валютной переоценки",
    "market_share": "растущих сегментов больше падающих → +1, наоборот → −1, поровну → 0; ±2 не ставится",
    "capital_adequacy": "в п.п.; «остаётся комфортным» и подобное — только если фраза есть в отчёте",
    "dividends": "«рекордные» +2, «вернёмся к рассмотрению» +1, отказ/перенос −2, не упоминается 0",
    "book_value_per_share": "изменение с начала года",
    "active_clients": "число клиентов банка, изменение с начала года",
    "digital_metrics": "только MAU основного приложения для частных лиц (иначе DAU); подписки и бизнес-приложения не в счёт",
    "tech_development": "+1 только при измеримом факте (дата, число, доля); общие слова → 0",
    "external_conditions": "оценивается среда (ставка, санкции, регулирование), а не результат банка",
    "ceo_tone": "«рекорд»/обязательство с цифрой +2; факты роста без оговорок +1; плюс и минус вместе 0; оговорки −1; антикризис −2",
}


def main():
    report = sys.argv[1] if len(sys.argv) > 1 else "2026_q2"
    spec = sys.argv[2] if len(sys.argv) > 2 else "v2_inplace"
    OUT.mkdir(parents=True, exist_ok=True)
    form = OUT / f"{report}_ANDREY.csv"
    assert not form.exists(), f"{form} уже есть — не перезаписываю"
    with form.open("w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["id", "блок", "показатель", "тип", "правило коротко",
                    "ОЦЕНКА (-2..2)", "ЦИТАТА из отчёта", "комментарий"])
        for pid, block, name, kind in INDICATORS:
            w.writerow([pid, block, name, kind, RULES.get(pid, ""), "", "", ""])
    (OUT / f"{report}_ПАМЯТКА.md").write_text(f"""# Ручная разметка отчёта {report}

Зачем: устойчивость (одинаковые ответы) и правильность (верные ответы) — разные вещи. Модель может стабильно
ошибаться. Твои оценки — эталон, с которым мы сравним модель. Поэтому в форме нет оценок модели: если их увидеть,
эталон перестанет быть независимым.

## Что делать
1. Открыть отчёт: `pdf/{report}.pdf` (читать удобнее оригинал, модель работает с распознанным текстом
   `text/{report}.txt`).
2. Открыть форму `{report}_ANDREY.csv` (лежит рядом с этой памяткой) в Numbers или Excel.
3. Для каждой из 24 строк заполнить три колонки:
   - **ОЦЕНКА** — целое число от −2 до +2 по `ИНСТРУКЦИЯ_ПО_РАЗМЕТКЕ.md` (рядом; спека модели — `specs/{spec}.md`);
   - **ЦИТАТА** — фраза из отчёта, на которой основана оценка (для нуля «не упоминается» можно оставить пустой);
   - **комментарий** — если правило спеки показалось двусмысленным, напиши почему. Это ценно само по себе.
4. Сохранить как CSV с тем же именем.

## Подсказки
- Оценка = влияние факта на акционера, а не направление цифры: рост резервов — минус, снижение CIR — плюс.
- Сумму считать не надо, её посчитает Python.
- Если сомневаешься между двумя значениями — поставь любое и обязательно напиши в комментарии, между чем выбирал.
  Такие места и есть главный результат работы.
- Ориентировочно 1–1,5 часа на отчёт. Спешить не нужно: один внимательный отчёт полезнее двух беглых.

## Что будет дальше
`src/compare_gold.py` сравнит твой вектор с прогонами всех версий спеки: по скольким показателям модель совпала
с тобой, где систематически расходится, и какая версия ближе к эталону. Это даст вторую ось — правильность —
рядом с устойчивостью.
""")
    print(f"форма: {form}\nпамятка: {OUT / f'{report}_ПАМЯТКА.md'}")


if __name__ == "__main__":
    main()
