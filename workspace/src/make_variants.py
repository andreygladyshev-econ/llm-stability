def write(name, text, source, note, version="v1"):
    d = texts.text_dir(version)
    p = d / f"{name}.txt"
    p.write_text(text)
    hashes_path = d / "hashes.json"
    h = json.loads(hashes_path.read_text())
    h[name] = {"sha256": hashlib.sha256(text.encode()).hexdigest(), "engine": f"производный от {source}",
               "note": note, "chars": len(text), "created": dt.datetime.now().isoformat(timespec="seconds")}
    hashes_path.write_text(json.dumps(h, ensure_ascii=False, indent=1))


def anon(version):
    """H15 на любой версии текста: имя банка и первого лица убраны, остальной текст не тронут."""
    for rep in DEV:
        t = (texts.text_dir(version) / f"{rep}.txt").read_text()
        for pat, sub in ANON:
            t = re.sub(pat, sub, t)
        left = set(re.findall(r"Сбер|Sber|Греф", t))
        assert not left, f"{rep}: осталось {left}"
        write(f"anon_{rep}", t, rep, f"обезличен: банк и первое лицо заменены (H15), текст {version}", version)
        print(f"anon_{rep} ({version}): {len(t)} символов")


def main():
    for rep in DEV:
        t = (TEXT / f"{rep}.txt").read_text()
        for pat, sub in ANON:
            t = re.sub(pat, sub, t)
        left = re.findall(r"Сбер|Sber|Греф", t)
        assert not left, f"{rep}: осталось {set(left)}"
        write(f"anon_{rep}", t, rep, "обезличен: банк и первое лицо заменены (H15)")
        print(f"anon_{rep}: {len(t)} символов")

    for name, rep, edits, ind, expect, forbid in COUNTERFACTS:
        t = (TEXT / f"{rep}.txt").read_text()
        for find, repl in edits:
            all_ = find.startswith("*")  # «*» — заменить все вхождения, иначе обязано быть ровно одно
            find = find.lstrip("*")
            # в распознанном тексте бывают неразрывные и двойные пробелы — ищем гибко
            pat = re.compile(r"\s+".join(re.escape(w) for w in find.split()))
            n = len(pat.findall(t))
            assert n == 1 or (all_ and n >= 1), f"{name}: фрагмент {find[:40]!r} встречается {n} раз"
            t = pat.sub(lambda _: repl, t, count=0 if all_ else 1)
        for bad in forbid:
            assert bad not in t, f"{name}: в тексте осталось {bad!r} — правка неполная"
        write(f"cf_{name}", t, rep, f"контрфакт по {ind}: {expect}")
        print(f"cf_{name}: {rep}, {ind}, правок {len(edits)} — {expect}")
    (ROOT / "notes" / "counterfacts.json").write_text(json.dumps(
        [{"name": f"cf_{n}", "base": r, "indicator": i, "expect": e, "edits": len(ed)}
         for n, r, ed, i, e, _ in COUNTERFACTS],
        ensure_ascii=False, indent=1))


